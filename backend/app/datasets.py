"""Reads the ETL tables (backend/data/db/*.parquet) for the API.

Tables are loaded once and reload themselves if the parquet changes (for example after
`python -m app.etl build`). The parquet files generated by the notebook in Colab also work:
just copy them to backend/data/db.
"""
import math
from threading import Lock

from .etl.config import TABLE_NAMES, path, status
from .etl.grid import AOIS, PILOTS, RADIUS_KM, cell_center, cell_id, zone_of

_cache: dict[str, tuple[float, object]] = {}
_lock = Lock()


class DatasetError(Exception):
    def __init__(self, status: int, msg: str):
        self.status, self.msg = status, msg


def table(name: str):
    """The table's DataFrame, or None if it hasn't been built yet."""
    import pandas as pd

    if name not in TABLE_NAMES:
        raise DatasetError(404, f"Tabla desconocida: {name}")
    p = path(name)
    if not p.exists():
        return None
    mtime = p.stat().st_mtime
    with _lock:
        hit = _cache.get(name)
        if hit and hit[0] == mtime:
            return hit[1]
        df = pd.read_parquet(p)
        _cache[name] = (mtime, df)
        return df


def _clean(v):
    """JSON-serializable values (NaN -> None, numpy -> python)."""
    if v is None:
        return None
    if hasattr(v, "item"):
        v = v.item()
    if isinstance(v, float) and not math.isfinite(v):
        return None
    if hasattr(v, "isoformat"):
        return v.isoformat()
    return v


def records(df, limit: int | None = None) -> list[dict]:
    if df is None:
        return []
    if limit is not None:
        df = df.head(limit)
    cols = list(df.columns)
    return [{c: _clean(v) for c, v in zip(cols, row)} for row in df.itertuples(index=False, name=None)]


def status_summary() -> dict:
    return {
        "tables": status(),
        "pilot_zones": zones(),
        "build_command": "cd backend && python -m app.etl build",
    }


def zones() -> list[dict]:
    return [{"id": z, "lat": c[0], "lon": c[1], "radius_km": RADIUS_KM, "bbox": AOIS[z]} for z, c in PILOTS.items()]


def table_rows(name: str, zone: str | None, cid: int | None, filters: dict, limit: int, offset: int) -> dict:
    df = table(name)
    if df is None:
        raise DatasetError(404, f"La tabla {name} aun no se ha construido. Ejecuta: python -m app.etl build {name}")
    if zone and "zona" in df:
        df = df[df["zona"] == zone]
    if cid is not None and "cell_id" in df:
        df = df[df["cell_id"] == cid]
    for c, v in filters.items():
        if c in df and v is not None:
            df = df[df[c].astype(str) == str(v)]
    total = len(df)
    return {"table": name, "total": total, "offset": offset, "limit": limit,
            "columns": list(df.columns), "rows": records(df.iloc[offset:offset + limit])}


def _by_cell(name: str, cid: int):
    df = table(name)
    if df is None or "cell_id" not in df:
        return None
    return df[df["cell_id"] == cid]


def cell(lat: float, lon: float) -> dict:
    """Everything the database knows about the 0.25-degree cell that contains the point."""
    cid = int(cell_id(lat, lon))
    clat, clon = cell_center(cid)
    out = {"cell_id": cid, "cell_center": {"lat": clat, "lon": clon}, "zone": zone_of(lat, lon),
           "in_database": False, "coverage": [], "gaez_actual": [], "gaez_suitability": [], "gaez_growing": [],
           "climatology": [], "indicators_recent": [], "landcover": [], "stations_validation": None}

    cov = _by_cell("coverage", cid)
    if cov is not None and len(cov):
        out["coverage"] = records(cov[["fuente", "disponible"]])
        out["in_database"] = bool(cov["disponible"].any())

    ga = _by_cell("gaez_actual", cid)
    if ga is not None and len(ga):
        ga = ga[~ga["es_grupo"]] if "es_grupo" in ga else ga
        last = ga[ga["year"] == ga["year"].max()]
        tot = last[last["water_supply"] == "Total"].sort_values("area_cosechada_kha", ascending=False)
        out["gaez_actual"] = records(tot[["crop", "crop_code", "year", "area_cosechada_kha", "produccion_kt",
                                            "rendimiento_t_ha"]])

    gs = _by_cell("gaez_suitability", cid)
    if gs is not None and len(gs):
        cols = [c for c in ("crop", "indicador", "regimen_agua", "tipo_riego", "input_level", "valor_std", "unidad_std")
                if c in gs]
        out["gaez_suitability"] = records(gs[cols])

    gg = _by_cell("gaez_growing", cid)
    if gg is not None and len(gg):
        out["gaez_growing"] = records(gg[[c for c in ("sub_theme_name", "variable", "units", "valor") if c in gg]])

    cl = _by_cell("climatology", cid)
    if cl is not None and len(cl):
        out["climatology"] = records(cl.sort_values(["fuente", "mes"]))

    ind = _by_cell("indicators_monthly", cid)
    if ind is not None and len(ind):
        out["indicators_recent"] = records(ind.sort_values(["año", "mes"]).tail(24))

    lc = _by_cell("landcover", cid)
    if lc is not None and len(lc):
        out["landcover"] = records(lc.sort_values(["año", "pct"], ascending=[True, False]))

    sv = _by_cell("stations_validation", cid)
    if sv is not None and len(sv):
        from .etl.stations import validation_summary

        out["stations_validation"] = {"summary": validation_summary(sv), "rows": records(sv)}
    return out


def zone_summary(zone: str) -> dict:
    """Aggregated summary of a pilot zone: main crops, recent drought and validation."""
    if zone not in PILOTS:
        raise DatasetError(404, "Zona piloto no encontrada")
    out = {"zone": zone, "center": dict(zip(("lat", "lon"), PILOTS[zone])), "bbox": AOIS[zone],
           "top_crops": [], "drought_recent": [], "stations_validation": [], "landcover_latest": []}

    ga = table("gaez_actual")
    if ga is not None:
        g = ga[(ga["zona"] == zone) & (ga["water_supply"] == "Total")]
        if "es_grupo" in g:
            g = g[~g["es_grupo"]]
        if len(g):
            g = g[g["year"] == g["year"].max()]
            top = (g.groupby("crop", as_index=False)
                     .agg(area_cosechada_kha=("area_cosechada_kha", "sum"), produccion_kt=("produccion_kt", "sum")))
            top["rendimiento_t_ha"] = top["produccion_kt"] / top["area_cosechada_kha"]
            out["top_crops"] = records(top.sort_values("area_cosechada_kha", ascending=False), 15)

    ind = table("indicators_monthly")
    if ind is not None:
        i = ind[ind["zona"] == zone]
        if len(i):
            m = (i.groupby(["año", "mes"], as_index=False)
                   .agg(z_humedad_radicular=("z_humedad_radicular", "mean"),
                        celdas_sequia=("nivel_sequia", lambda s: int((s >= 1).sum())),
                        celdas=("cell_id", "nunique")))
            out["drought_recent"] = records(m.sort_values(["año", "mes"]).tail(24))

    sv = table("stations_validation")
    if sv is not None:
        from .etl.stations import validation_summary

        s = sv[sv["zona"] == zone]
        if len(s):
            out["stations_validation"] = validation_summary(s)

    lc = table("landcover")
    if lc is not None:
        l = lc[lc["zona"] == zone]
        if len(l):
            l = l[l["año"] == l["año"].max()]
            agg = l.groupby("clase", as_index=False)["pct"].mean().sort_values("pct", ascending=False)
            out["landcover_latest"] = records(agg)
    return out
